    """2026-11-01 到 2026-11-15 共 96 个快照：前 6 天每天 7 个，后 9 天每天 6 个。

    创建方式在 定时调度 / 触发式 / 手动创建 之间轮换；SNAP-20261110-01 最近被
    恢复页面访问（最近访问时间 2026-11-16），用于演示创建时间与最近访问时间
    产生保留冲突时，按保留边界分别处理的口径。
    """
    tables = [
        "dwd_trade_orders",
        "dwd_user_profiles",
        "dwd_payment_flows",
        "dwd_inventory_changes",
        "dwd_logistics_events",
    ]
    methods = ["定时调度", "触发式", "手动创建"]
    rows: list[dict[str, Any]] = []
    sid = 0
    for day in range(1, 16):
        date = f"2026-11-{day:02d}"
        count = 7 if day <= 6 else 6
        for seq in range(1, count + 1):
            sid += 1
            rows.append({
                "id": sid,
                "status": "保留中",
                "pending": True,
                "abnormal": False,
                "快照编号": f"SNAP-202611{day:02d}-{seq:02d}",
                "表名称": tables[(sid - 1) % len(tables)],
                "快照时间": date,
                "快照版本": f"v1.{sid}",
                "快照大小": f"{96 + (sid % 5) * 32}MB",
                "保留天数": 7,
                "创建方式": methods[(sid - 1) % len(methods)],
                "快照状态": "保留中",
                "最近访问时间": date,
            })
    # SNAP-20261110-01 最近被恢复页面访问
    for row in rows:
        if row["快照编号"] == "SNAP-20261110-01":
            row["最近访问时间"] = "2026-11-16"
    return rows


